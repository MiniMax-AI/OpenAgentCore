package sandbox

import (
	"encoding/json"
	"fmt"
	"github.com/MiniMax-AI/OpenAgentCore/services/core/internal/workspacefs"
	"reflect"
	"strings"
)

// This contract owns numeric bounds and canonical field order.
// The node installer (node_spec.py) and the TypeScript client
// (deployment-contract.ts) consume its generated projections.
const minimumDiskMiB uint32 = 1024

type resourceRule struct {
	Name     string `json:"name"`
	Min      uint32 `json:"min"`
	Max      uint32 `json:"max"`
	OmitZero bool   `json:"omit_zero"`
	Message  string `json:"-"`
}

var resourceContract = []resourceRule{
	{"cpus", 1, 255, false, "cpus must be 1..255 and memory_mib must be 512..1048576"},
	{"memory_mib", 512, 1048576, false, "cpus must be 1..255 and memory_mib must be 512..1048576"},
	{"root_disk_mib", 0, ^uint32(0), true, ""},
	{"environment_disk_mib", 0, ^uint32(0), true, ""},
}

// ProviderProjection is one registered Provider in the generated projections.
// Setup reaches the TypeScript client only: the node installer needs no setup copy.
type ProviderProjection struct {
	Mode DeploymentMode `json:"mode"`
	DeploymentPolicy
	Setup *ProviderSetup `json:"setup,omitempty"`
}

// ProviderSetup is a Provider's setup declaration with the configuration
// requirements the console needs beside it.
type ProviderSetup struct {
	SetupDeclaration
	Credential   Requirement `json:"credential"`
	PublicOrigin Requirement `json:"public_origin"`
	Discovery    bool        `json:"discovery"`
}

// DeploymentContract generates the installer and TypeScript client projections
// of one contract. Struct order is checked first because it also defines Go's
// canonical JSON bytes.
func DeploymentContract(providers map[string]ProviderProjection) (python, typescript string) {
	for _, item := range []struct {
		value any
		names []string
	}{
		{Resources{}, resourceNames()},
	} {
		typ := reflect.TypeOf(item.value)
		if typ.NumField() != len(item.names) {
			panic("deployment contract field count differs")
		}
		for i, name := range item.names {
			if strings.Split(typ.Field(i).Tag.Get("json"), ",")[0] != name {
				panic("deployment contract field order differs")
			}
		}
	}
	workspaceFields := []string{}
	workspaceType := reflect.TypeFor[workspacefs.Declaration]()
	for field := range workspaceType.NumField() {
		workspaceFields = append(workspaceFields, strings.Split(workspaceType.Field(field).Tag.Get("json"), ",")[0])
	}
	render := func(providers map[string]ProviderProjection) string {
		raw, _ := json.Marshal(struct {
			WorkspaceFields []string                      `json:"workspace_fields"`
			Resources       []resourceRule                `json:"resources"`
			Providers       map[string]ProviderProjection `json:"providers"`
			MinimumDisk     uint32                        `json:"minimum_disk"`
		}{workspaceFields, resourceContract, providers, minimumDiskMiB})
		return string(raw)
	}
	installer := make(map[string]ProviderProjection, len(providers))
	for kind, p := range providers {
		p.Setup = nil
		installer[kind] = p
	}
	return "# BEGIN GENERATED DEPLOYMENT CONTRACT\n# Generated from sandbox/deployment_contract.go; do not edit.\n_CONTRACT = json.loads(" + fmt.Sprintf("%q", render(installer)) + ")\n# END GENERATED DEPLOYMENT CONTRACT",
		"// Code generated by services/core/cmd/specification-contract from sandbox/deployment_contract.go; DO NOT EDIT.\n\nexport const deploymentContract = " + render(providers) + " as const;\n"
}
func resourceNames() []string {
	var names []string
	for _, r := range resourceContract {
		names = append(names, r.Name)
	}
	return names
}
