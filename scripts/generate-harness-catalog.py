#!/usr/bin/env python3
"""Generate static Harness registrations; native execution stays in adapters."""

import argparse
import json
from pathlib import Path
import re
import subprocess
from pprint import pformat

ROOT = Path(__file__).resolve().parent.parent
DECLARATIONS = Path("internal/harnessconfig")
MODULE = "github.com/MiniMax-AI/OpenAgentCore"
HEADER = "// Code generated by scripts/generate-harness-catalog.py; DO NOT EDIT.\n"
SOURCE = "https://github.com/MiniMax-AI/OpenAgentCore/blob/main/"


def packages(root=ROOT):
    """The Harness packages: every directory under internal/harnessconfig with a declaration.go."""
    result = sorted(path.parent.name for path in (root / DECLARATIONS).glob("*/declaration.go"))
    if not result:
        raise ValueError("No Harness declarations found")
    for name in result:
        if not re.fullmatch(r"[a-z][a-z0-9]*", name):
            raise ValueError("Invalid Harness package name: " + name)
        if not re.search(r"^var Declaration = harnessconfig\.Declaration\{", (root / DECLARATIONS / name / "declaration.go").read_text(), re.M):
            raise ValueError(name + "/declaration.go must declare `var Declaration = harnessconfig.Declaration{`")
        if not (root / "apps/daemon/internal/agent" / name).is_dir():
            raise ValueError("Missing Runtime adapter package apps/daemon/internal/agent/" + name)
    return result


def load_declared():
    """Dump the built Go declarations; the Go values are the only authored source."""
    return json.loads(subprocess.run(["go", "run", "./scripts/harness-catalog"], cwd=ROOT,
                                     text=True, check=True, capture_output=True).stdout)


def go(source):
    return subprocess.run(["gofmt"], input=HEADER + source, text=True,
                          check=True, capture_output=True).stdout


def render_installer(protocols):
    return ("# Code generated by scripts/generate-harness-catalog.py; DO NOT EDIT.\n"
            "# Protocol support comes from the Go Harness declarations.\n"
            "PROVIDERS = " + pformat(protocols, sort_dicts=True, width=100) + "\n")


def render_client(harnesses, protocols):
    kinds = ", ".join(json.dumps(entry["kind"]) for entry in harnesses)
    labels = "\n".join(f'  {json.dumps(entry["kind"])}: {json.dumps(entry["label"])},' for entry in harnesses)
    return HEADER + f"""
export const coreHarnessKinds = [{kinds}] as const;
export type CoreHarnessKind = (typeof coreHarnessKinds)[number];
export const coreHarnessNames: Record<CoreHarnessKind, string> = {{
{labels}
}};
export const modelProviderProtocols = [{", ".join(json.dumps(protocol) for protocol in protocols)}] as const;
export type ModelProviderProtocol = (typeof modelProviderProtocols)[number];
"""


def render_registrations(names):
    """Go projections that need only the package names."""
    imports = "\n".join(f'\t"{MODULE}/internal/harnessconfig/{name}"' for name in names)
    declarations = ", ".join(f"{name}.Declaration" for name in names)
    adapters = "\n".join(f'\t"{MODULE}/apps/daemon/internal/agent/{name}"' for name in names)
    bindings = ", ".join(f"{name}.Declaration" for name in names)
    return {
        Path("internal/harnessconfig/builtin/registry.go"): go(f"""package builtin

import (
    "{MODULE}/internal/harnessconfig"
{imports}
)

var registry = harnessconfig.NewRegistry({declarations})
"""),
        Path("apps/daemon/internal/cli/harness_declarations.go"): go(f"""package cli

import (
    "{MODULE}/apps/daemon/internal/agent"
{adapters}
)

// harnessDeclarations binds every built-in Harness declaration to its Runtime adapter.
var harnessDeclarations = []agent.Declaration{{{bindings}}}
"""),
    }


def render_docs(harnesses):
    tick = chr(96)
    rows = "\n".join(
        f'| {tick}{h["kind"]}{tick} | {h["label"]} | [{tick}{h["package"]}/declaration.go{tick}]({SOURCE}internal/harnessconfig/{h["package"]}/declaration.go) |'
        for h in harnesses)
    return {
        Path("contracts/agents-api/harness-catalog.md"): f"""---
title: "Built-in Harness registrations"
---

[//]: # (Generated by scripts/generate-harness-catalog.py; DO NOT EDIT.)
# Built-in Harness registrations

Each Harness is the one {tick}declaration.go{tick} in its {tick}internal/harnessconfig/<package>{tick} directory. Adding a directory with a {tick}declaration.go{tick} registers the Harness; {tick}make generate-harness-catalog{tick} regenerates the registrations and this page, and {tick}make check-harness-catalog{tick} checks them.

| Identifier | Display name | Declaration |
| --- | --- | --- |
{rows}

These registrations describe the build. Which Harnesses a deployment enables is the {tick}OAC_HARNESSES{tick} [process setting](../../docs/configuration.md#settings), [Harness capabilities](./harness-capabilities.md) lists what each Harness supports, and a connected Runtime reports its own availability. [Harness protocol](./harness-onboarding.md) describes the adapter and packaging steps.
""",
        Path("contracts/agents-api/zh/harness-catalog.md"): f"""---
title: "内置 Harness 注册"
---

[//]: # (Generated by scripts/generate-harness-catalog.py; DO NOT EDIT.)
# 内置 Harness 注册 {{#built-in-harness-registrations}}

每个 Harness 对应 {tick}internal/harnessconfig/<package>{tick} 目录中唯一的 {tick}declaration.go{tick}。新增包含 {tick}declaration.go{tick} 的目录即注册该 Harness；{tick}make generate-harness-catalog{tick} 重新生成注册代码和本页，{tick}make check-harness-catalog{tick} 检查生成结果。

| 标识符 | 显示名称 | 声明 |
| --- | --- | --- |
{rows}

这些注册描述当前构建。部署启用的 Harness 由 {tick}OAC_HARNESSES{tick} [进程设置](../../../docs/zh/configuration.md#settings)决定；[Harness 能力](./harness-capabilities.md)列出各 Harness 的支持范围，连接的 Runtime 报告自身可用性。[Harness protocol](./harness-onboarding.md)介绍适配器和打包步骤。
""",
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    names = packages()
    stale = []

    def projection(relative, content):
        path = ROOT / relative
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(relative))
        else:
            path.write_text(content)

    for relative, content in render_registrations(names).items():
        projection(relative, content)
    # The Go dump builds against the registration, so a stale registration must
    # fail (or be refreshed) before the declarations can be projected.
    if stale:
        raise SystemExit("Stale Harness catalog projections; run make generate-harness-catalog:\n" + "\n".join(stale))
    declared = load_declared()
    harnesses = declared["harnesses"]
    for harness in harnesses:
        harness["package"] = harness["kind"].replace("_", "")
        if harness["package"] not in names:
            raise SystemExit("Harness " + harness["kind"] + " must live in internal/harnessconfig/" + harness["package"])
    if len(harnesses) != len(names):
        raise SystemExit("Registered Harnesses differ from the declaration packages")
    for relative, content in render_docs(harnesses).items():
        projection(relative, content)
    projection(Path("scripts/acceptance/harness_catalog.py"), render_installer({h["kind"]: h["protocols"] for h in harnesses}))
    projection(Path("packages/agents-client/src/harness-catalog.ts"), render_client(harnesses, declared["protocols"]))
    if stale:
        raise SystemExit("Stale Harness catalog projections; run make generate-harness-catalog:\n" + "\n".join(stale))


if __name__ == "__main__":
    main()
